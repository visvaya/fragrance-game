-- Yearly limited editions ("Flowerbomb Limited Edition", "1 Million Collector's Edition") carry
-- their year only at the end of the Parfumo address; the source year field is empty. The ETL now
-- takes that year (scripts/etl.py, year_from_address), so these editions get their own keys. The
-- list comes from that function run on the 2026-11 source file: for each stored row, the year of
-- the most rated source row behind it (the one keep-first deduplication kept). 83 groups whose top
-- rows tie on ratings are left out, because the stored edition cannot be told apart. None of the
-- rows is certain. A row keeps its empty year if another row already has the target key.
-- source_record_slug and the fingerprints follow on the next import, which matches these rows by
-- brand, name, concentration and year.
--
-- Non-ASCII characters are written as U& escapes so the file stays ASCII.

